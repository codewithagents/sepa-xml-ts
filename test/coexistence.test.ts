// ---------------------------------------------------------------------------
// Constants
// ---------------------------------------------------------------------------

const DEBTOR_IBAN = 'DE89370400440532013000'
const CREDITOR_IBAN = 'DE65200400300234567000'
const CREDITOR_ID = 'DE98ZZZ09999999999'

// ---------------------------------------------------------------------------
// Helper: build a pain.001.001.03 XML with the sepa devDependency
// ---------------------------------------------------------------------------

function buildPain001003(): string {
  const doc = new SEPA.Document('pain.001.001.03')
  doc.grpHdr.id = 'COEX-CT-001'
  doc.grpHdr.created = new Date('2026-06-01T08:00:00Z')
  doc.grpHdr.initiatorName = 'Coexistence Test GmbH'

  const info = doc.createPaymentInfo()
  info.requestedExecutionDate = new Date('2026-06-10')
  info.debtorIBAN = DEBTOR_IBAN
  info.debtorBIC = 'COBADEFFXXX'
  info.debtorName = 'Coexistence Test GmbH'

  const tx1 = info.createTransaction()
  tx1.creditorName = 'Supplier One'
  tx1.creditorIBAN = CREDITOR_IBAN
  tx1.amount = 12.34
  tx1.end2endId = 'COEX-E2E-0001'
  // Both transactions need remittanceInfo so sepa does not emit <Ustrd/> (empty element),
  // which would fail the .03 XSD minLength constraint.
  tx1.remittanceInfo = 'Payment COEX/01'

  const tx2 = info.createTransaction()
  tx2.creditorName = 'Supplier Two'
  tx2.creditorIBAN = CREDITOR_IBAN
  tx2.amount = 56.78
  tx2.end2endId = 'COEX-E2E-0002'
  tx2.remittanceInfo = 'Invoice COEX/01'

  info.addTransaction(tx1)
  info.addTransaction(tx2)
  doc.addPaymentInfo(info)

  return doc.toString()
}

// ---------------------------------------------------------------------------
// Helper: minimal valid pain.008.001.02 XML
//
// Element ordering follows PaymentInstructionInformation4 in the .02 XSD:
//   PmtInfId, PmtMtd, PmtTpInf, ReqdColltnDt, Cdtr, CdtrAcct, CdtrAgt (required),
//   CdtrSchmeId, DrctDbtTxInf
//
// Element ordering in DrctDbtTxInf (DirectDebitTransactionInformation9):
//   PmtId, InstdAmt, DrctDbtTx (mandate), DbtrAgt (required), Dbtr, DbtrAcct
// ---------------------------------------------------------------------------

