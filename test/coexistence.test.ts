describe('coexistence: validateXsd handles all four namespaces', () => {
  it('validates a pain.001.001.03 document as valid=true', async () => {
    const xml = buildPain001003()
    const result = await validateXsd(xml)
    expect(result.errors).toHaveLength(0)
    expect(result.valid).toBe(true)
  })

  it('validates a pain.008.001.02 document as valid=true', async () => {
    const result = await validateXsd(PAIN008_002_XML)
    expect(result.valid).toBe(true)
  })

  it('validates a pain.001.001.09 document (write target) as valid=true', async () => {
    const doc: CreditTransferDocument = {
      messageId: 'COEX-VALIDATE-001',
      createdAt: '2026-06-01T08:00:00Z',
      initiatingParty: 'Test GmbH',
      batches: [
        {
          id: 'BATCH-001',
          executionDate: '2026-06-10',
          debtor: { name: 'Test GmbH', iban: DEBTOR_IBAN },
          transfers: [
            {
              endToEndId: 'E2E-0001',
              amount: euros('1.00'),
              creditor: { name: 'Recipient', iban: CREDITOR_IBAN },
            },
          ],
        },
      ],
    }
    const xml = writeCreditTransfer(doc)
    const result = await validateXsd(xml)
    expect(result.valid, `XSD errors: ${result.errors.join(', ')}`).toBe(true)
  })

  it('returns valid=false with descriptive error for an unknown namespace', async () => {
    const xml = `<?xml version="1.0"?><Document xmlns="urn:example:unknown"><SomeEl/></Document>`
    const result = await validateXsd(xml)
    expect(result.valid).toBe(false)
    expect(result.errors[0]).toMatch(/Unsupported namespace/i)
  })

  it('returns valid=false with descriptive error when xmlns is missing', async () => {
    const xml = `<?xml version="1.0"?><Document><SomeEl/></Document>`
    const result = await validateXsd(xml)
    expect(result.valid).toBe(false)
    expect(result.errors[0]).toMatch(/Could not detect/i)
  })
})
