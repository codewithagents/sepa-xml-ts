// ---------------------------------------------------------------------------
// Task 3a: parse pain.001.001.03 generated by sepa library
// ---------------------------------------------------------------------------

describe('coexistence: parse() reads pain.001.001.03 (generated by sepa library)', () => {
  it('returns ok:true with type="pain.001"', () => {
    const xml = buildPain001003()
    const result = parse(xml)
    expect(result.ok, result.ok ? '' : (result as { error: string }).error).toBe(true)
    if (!result.ok) throw new Error('expected ok:true')
    expect(result.type).toBe('pain.001')
  })

  it('returns version="pain.001.001.03"', () => {
    const xml = buildPain001003()
    const result = parse(xml)
    if (!result.ok || result.type !== 'pain.001') throw new Error('expected ok pain.001')
    expect(result.version).toBe('pain.001.001.03')
  })

  it('messageId round-trips correctly', () => {
    const xml = buildPain001003()
    const result = parse(xml)
    if (!result.ok || result.type !== 'pain.001') throw new Error('expected ok pain.001')
    expect(result.data.messageId).toBe('COEX-CT-001')
  })

  it('initiatingParty round-trips correctly', () => {
    const xml = buildPain001003()
    const result = parse(xml)
    if (!result.ok || result.type !== 'pain.001') throw new Error('expected ok pain.001')
    expect(result.data.initiatingParty).toBe('Coexistence Test GmbH')
  })

  it('executionDate is YYYY-MM-DD (plain text in .03, not wrapped in Dt)', () => {
    const xml = buildPain001003()
    const result = parse(xml)
    if (!result.ok || result.type !== 'pain.001') throw new Error('expected ok pain.001')
    expect(result.data.batches).toHaveLength(1)
    expect(result.data.batches[0]?.executionDate).toBe('2026-06-10')
  })

  it('debtor IBAN is preserved', () => {
    const xml = buildPain001003()
    const result = parse(xml)
    if (!result.ok || result.type !== 'pain.001') throw new Error('expected ok pain.001')
    expect(result.data.batches[0]?.debtor.iban).toBe(DEBTOR_IBAN)
  })

  it('debtor BIC is preserved (sepa library uses <BIC> not <BICFI>)', () => {
    const xml = buildPain001003()
    const result = parse(xml)
    if (!result.ok || result.type !== 'pain.001') throw new Error('expected ok pain.001')
    expect(result.data.batches[0]?.debtor.bic).toBe('COBADEFFXXX')
  })

  it('both transfers have correct endToEndIds', () => {
    const xml = buildPain001003()
    const result = parse(xml)
    if (!result.ok || result.type !== 'pain.001') throw new Error('expected ok pain.001')
    const transfers = result.data.batches[0]?.transfers
    expect(transfers).toHaveLength(2)
    expect(transfers?.[0]?.endToEndId).toBe('COEX-E2E-0001')
    expect(transfers?.[1]?.endToEndId).toBe('COEX-E2E-0002')
  })

  it('amounts are correct as Money minorUnits', () => {
    const xml = buildPain001003()
    const result = parse(xml)
    if (!result.ok || result.type !== 'pain.001') throw new Error('expected ok pain.001')
    const transfers = result.data.batches[0]?.transfers
    // 12.34 EUR = 1234 minor units
    expect(transfers?.[0]?.amount.minorUnits).toBe(1234n)
    expect(transfers?.[0]?.amount.currencyCode).toBe('EUR')
    // 56.78 EUR = 5678 minor units
    expect(transfers?.[1]?.amount.minorUnits).toBe(5678n)
  })

  it('creditor IBANs are preserved', () => {
    const xml = buildPain001003()
    const result = parse(xml)
    if (!result.ok || result.type !== 'pain.001') throw new Error('expected ok pain.001')
    const transfers = result.data.batches[0]?.transfers
    expect(transfers?.[0]?.creditor.iban).toBe(CREDITOR_IBAN)
    expect(transfers?.[1]?.creditor.iban).toBe(CREDITOR_IBAN)
  })
})

