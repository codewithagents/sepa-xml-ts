/**
 * Coexistence tests: parse() reads legacy SEPA formats into the same model.
 *
 * pain.001.001.03: generated via the `sepa` devDependency (same library used in
 * differential.test.ts). Verifies that parse() normalises it to type="pain.001"
 * with correct model fields.
 *
 * pain.008.001.02: hand-built minimal valid XML string, first validated against
 * the .02 XSD (oracle), then parsed and model fields checked.
 *
 * validateXsd tests confirm all four namespaces are handled by the validator.
 */

import { describe, it, expect } from 'vitest'
import SEPA from 'sepa'
